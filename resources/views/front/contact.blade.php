            type: "POST",
            data: formData,
            dataType: "json",
            beforeSend: function () {
                $form.find('.cf_submit_btn').prop('disabled', true).text('Sending...');
            },
            success: function (res) {
                $form.find('.cf_submit_btn').prop('disabled', false).text('Request a Quote');
